import json
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
try:
    import dev

    build = dev.build_ui_bundle
except (ImportError, AttributeError) as error:
    print(error, file=sys.stderr)
    print(json.dumps({"regression_result": "error"}))
    raise SystemExit(2)


def main():
    scratch = Path(__file__).resolve().parents[2] / ".clutch/scratch"
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=scratch) as temporary:
        base = Path(temporary)
        main_root, wt = base / "main", base / "wt"
        executable = main_root / "node_modules/.bin/esbuild"
        executable.parent.mkdir(parents=True)
        executable.write_text("")
        gitdir = main_root / ".git/worktrees/wt"
        gitdir.mkdir(parents=True)
        wt.mkdir()
        (wt / ".git").write_text(f"gitdir: {gitdir}\n")
        for name in ("vscode-clutchwork/media/view.css", "clutch/ui/dashboard.css", "vscode-clutchwork/media/ticket-lifecycle.svg", "clutch/ui/app.js"):
            path = wt / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("asset")
        calls = []

        def fake_run(argv, **kwargs):
            calls.append((argv, kwargs))
            if not Path(argv[0]).is_file():
                raise FileNotFoundError(argv[0])
            return SimpleNamespace(returncode=0, stdout="console.log(1);", stderr="")

        output = wt / "dashboard.html"
        try:
            build(root=wt, out=output, run_cmd=fake_run)
        except RuntimeError as error:
            print(error, file=sys.stderr)
            return False
        return bool(calls and calls[0][0][0] == str(executable) and calls[0][1].get("env", {}).get("NODE_PATH") == str(main_root / "node_modules") and output.is_file())


passed = main()
print(json.dumps({"regression_result": "pass" if passed else "defect"}))
raise SystemExit(0 if passed else 1)
